-- Motivo de no avance de Ofertas — Pipeline del Portal de Agentes (/admin/agent/pipeline)
-- Fecha: 2026-08-04
--
-- Toda oferta clasificada como «Expirada» debe pedir al agente la razón por la que no avanzó
-- de etapa (hoy se pierde la causa comercial). La etapa `expiradas` es DERIVADA en el front
-- (classifyOffer), no persistida → el registro se ancla a id_oferta, no a un estatus.
--
-- Construye:
--   1. Catálogo `motivos_no_avance_oferta` (razones estandarizadas, claves estables).
--   2. Registro `ofertas_no_avance` (una razón vigente por oferta vía índice único parcial).
--   3. Vista `v_ofertas_no_avance` (motivo resuelto por oferta, security_invoker, para tableros).
--
-- Convención de esquema: ambas tablas tienen activo, fecha_creacion y fecha_actualizacion, y un
-- trigger BEFORE UPDATE que refresca fecha_actualizacion vía la función existente del esquema base
-- public.set_fecha_actualizacion() (NEW.fecha_actualizacion = now()).
--
-- El front usa DDL probe: mientras las tablas no existan muestra «pendiente de habilitar».
-- La captura se rige por el permiso `actualizar` (id 3) del submenú existente /admin/agent/pipeline;
-- NO se crea menú/submenú nuevo.
--
-- Idempotente: CREATE TABLE/INDEX IF NOT EXISTS, CREATE OR REPLACE VIEW,
-- DROP TRIGGER/POLICY IF EXISTS + CREATE, ON CONFLICT (clave) DO UPDATE. Sin BEGIN/COMMIT
-- (CI/CD envuelve en tx). El NOTIFY final se entrega al commit de esa tx.

-- ── 1. Catálogo de motivos ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.motivos_no_avance_oferta (
  id                  smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave               text         NOT NULL UNIQUE,
  nombre              text         NOT NULL,
  descripcion         text,
  requiere_comentario boolean      NOT NULL DEFAULT false,
  es_recuperable      boolean      NOT NULL DEFAULT true,
  orden               smallint     NOT NULL DEFAULT 100,
  activo              boolean      NOT NULL DEFAULT true,
  fecha_creacion      timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE  public.motivos_no_avance_oferta IS
  'Catálogo de razones por las que una oferta no avanzó a la siguiente etapa del pipeline.';
COMMENT ON COLUMN public.motivos_no_avance_oferta.clave IS
  'Slug estable consumido por el front; no cambiar una vez publicado.';
COMMENT ON COLUMN public.motivos_no_avance_oferta.requiere_comentario IS
  'Si es true, el front obliga a capturar comentario antes de guardar.';
COMMENT ON COLUMN public.motivos_no_avance_oferta.es_recuperable IS
  'true = el prospecto puede retomarse (timing, presupuesto); false = caída definitiva.';

CREATE INDEX IF NOT EXISTS idx_motivos_no_avance_oferta_activo
  ON public.motivos_no_avance_oferta (activo, orden);

DROP TRIGGER IF EXISTS trg_motivos_no_avance_oferta_touch ON public.motivos_no_avance_oferta;
CREATE TRIGGER trg_motivos_no_avance_oferta_touch
  BEFORE UPDATE ON public.motivos_no_avance_oferta
  FOR EACH ROW EXECUTE FUNCTION public.set_fecha_actualizacion();

-- ── 2. Registro por oferta ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.ofertas_no_avance (
  id                  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oferta           integer      NOT NULL
                        REFERENCES public.ofertas (id) ON DELETE CASCADE,
  id_motivo           smallint     NOT NULL
                        REFERENCES public.motivos_no_avance_oferta (id),
  comentario          text,
  registrado_por      text,
  activo              boolean      NOT NULL DEFAULT true,
  fecha_creacion      timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE  public.ofertas_no_avance IS
  'Razón capturada por el agente de por qué una oferta expirada no avanzó de etapa.';
COMMENT ON COLUMN public.ofertas_no_avance.registrado_por IS
  'Email del usuario que capturó la razón (no FK: puede capturarla un admin dado de baja después).';

-- Una sola razón vigente por oferta (permite corregirla con UPDATE).
CREATE UNIQUE INDEX IF NOT EXISTS uq_ofertas_no_avance_oferta_activa
  ON public.ofertas_no_avance (id_oferta) WHERE activo;

CREATE INDEX IF NOT EXISTS idx_ofertas_no_avance_motivo
  ON public.ofertas_no_avance (id_motivo) WHERE activo;

-- Mantener fecha_actualizacion (función existente del esquema base).
DROP TRIGGER IF EXISTS trg_ofertas_no_avance_touch ON public.ofertas_no_avance;
CREATE TRIGGER trg_ofertas_no_avance_touch
  BEFORE UPDATE ON public.ofertas_no_avance
  FOR EACH ROW EXECUTE FUNCTION public.set_fecha_actualizacion();

