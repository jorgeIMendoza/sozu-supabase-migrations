-- ── 4. Vista de reporte ─────────────────────────────────────────────────────
CREATE OR REPLACE VIEW public.v_ofertas_no_avance
WITH (security_invoker = true) AS
SELECT
  na.id_oferta,
  o.email_creador,
  o.fecha_generacion,
  o.id_propiedad,
  o.id_producto,
  o.id_persona_lead,
  m.clave           AS motivo_clave,
  m.nombre          AS motivo_nombre,
  m.es_recuperable,
  na.comentario,
  na.registrado_por,
  na.fecha_creacion
FROM public.ofertas_no_avance na
JOIN public.motivos_no_avance_oferta m ON m.id = na.id_motivo
JOIN public.ofertas o                  ON o.id = na.id_oferta
WHERE na.activo;

COMMENT ON VIEW public.v_ofertas_no_avance IS
  'Motivo vigente de no avance por oferta, resuelto contra el catálogo. Para tableros.';

-- ── 5. RLS y permisos ───────────────────────────────────────────────────────
ALTER TABLE public.motivos_no_avance_oferta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ofertas_no_avance        ENABLE ROW LEVEL SECURITY;

-- Catálogo: lectura pública autenticada/anónima (igual que el resto de catálogos).
DROP POLICY IF EXISTS motivos_no_avance_oferta_select ON public.motivos_no_avance_oferta;
CREATE POLICY motivos_no_avance_oferta_select
  ON public.motivos_no_avance_oferta
  FOR SELECT TO anon, authenticated
  USING (true);

-- Registro: lectura para cualquier usuario autenticado (admin y dirección auditan).
DROP POLICY IF EXISTS ofertas_no_avance_select ON public.ofertas_no_avance;
CREATE POLICY ofertas_no_avance_select
  ON public.ofertas_no_avance
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS ofertas_no_avance_insert ON public.ofertas_no_avance;
CREATE POLICY ofertas_no_avance_insert
  ON public.ofertas_no_avance
  FOR INSERT TO authenticated
  WITH CHECK ((SELECT auth.uid()) IS NOT NULL);

DROP POLICY IF EXISTS ofertas_no_avance_update ON public.ofertas_no_avance;
CREATE POLICY ofertas_no_avance_update
  ON public.ofertas_no_avance
  FOR UPDATE TO authenticated
  USING ((SELECT auth.uid()) IS NOT NULL)
  WITH CHECK ((SELECT auth.uid()) IS NOT NULL);

-- Sin política de DELETE: la corrección se hace por UPDATE.

-- Las columnas son IDENTITY, no `serial`: no se requiere GRANT sobre la secuencia.
GRANT SELECT                   ON public.motivos_no_avance_oferta TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE   ON public.ofertas_no_avance        TO authenticated;
GRANT SELECT                   ON public.v_ofertas_no_avance      TO authenticated;

-- Refrescar el cache de esquema de PostgREST para que el front vea las tablas
-- nuevas y la relación embebida `ofertas_no_avance → motivos_no_avance_oferta`.
NOTIFY pgrst, 'reload schema';
