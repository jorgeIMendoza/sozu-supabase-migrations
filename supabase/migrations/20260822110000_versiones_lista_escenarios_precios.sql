--   WHERE table_schema='public' AND table_name='versiones_lista'
--     AND grantee IN ('anon','authenticated') ORDER BY grantee, privilege_type;
--   -- esperado: anon sin filas; authenticated con SELECT, INSERT, UPDATE y sin DELETE
--
--   SELECT count(*) FROM public.versiones_lista;   -- esperado: 0, nace vacia
--
-- ═══════════════════════════════════════════════════════════════════════════════
-- TRES COSAS QUE CONVIENE SABER ANTES DE CONSTRUIR CONTRA ESTA TABLA
-- ═══════════════════════════════════════════════════════════════════════════════
--
-- 1) EL SUPER ADMINISTRADOR TAMPOCO PUEDE RENOMBRAR UNA PUBLICADA.
--    El diagnostico justifica darle UPDATE sobre cualquiera con el caso del "escenario mal
--    nombrado por quien ya no esta en la empresa". Eso funciona en borradores, pero el
--    trigger de inmutabilidad se aplica a TODOS por igual: sobre una publicada, el unico
--    UPDATE que pasa es archivarla. Es coherente con que sea el precio con el que se
--    vendio, pero significa que un nombre equivocado en una lista ya publicada se queda
--    asi. Si eso no es lo deseado, la excepcion tendria que escribirse en el trigger.
--
-- 2) LA NUMERACION PUEDE DAR 23505 EN CONCURRENCIA, POR DISEÑO.
--    El trigger lee MAX(numero) y eso no serializa: dos altas simultaneas en el mismo
--    proyecto obtienen el mismo numero y la segunda choca contra el indice unico. El
--    documento lo dice —"el indice unico es lo que garantiza que no se repita"— asi que el
--    front debe reintentar ante 23505 en vez de mostrar un error definitivo.
--
-- 3) `creada_por` NO ADMITE INSERCIONES SIN SESION.
--    Es NOT NULL con DEFAULT auth.uid(), que devuelve NULL cuando no hay JWT. Una insercion
--    con service_role —una Edge Function, un job— debe enviar el uuid explicitamente o
--    violara el NOT NULL. Hoy el modulo escribe desde el navegador como authenticated, asi
--    que no aplica; queda anotado para el dia que se automatice.
--
-- ─── Front ────────────────────────────────────────────────────────────────────
-- El modulo ya hace prueba de existencia de la tabla: mientras no este, guarda en
-- localStorage y avisa en pantalla que los escenarios no se comparten. Al aplicarse empieza
-- a usarla sin ningun cambio.
--
-- Lo que ya esta en localStorage NO se migra solo. Si hay escenarios que valga la pena
-- conservar, hay que volver a guardarlos con el motor retomado.
